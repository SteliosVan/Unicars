Future<void> requestLocationPermission() async {
  var status = await Permission.location.request();
  if (status.isGranted) {
    print('Permission granted');
  } else {
    print('Permission denied');
  }
}

void setupFirebaseMessaging() async {
  FirebaseMessaging messaging = FirebaseMessaging.instance;

  // Ζήτα άδεια για ειδοποιήσεις
  NotificationSettings settings = await messaging.requestPermission();

  if (settings.authorizationStatus == AuthorizationStatus.authorized) {
    print('User granted permission');
  }

  // Πάρε το FCM token της συσκευής
  String? token = await messaging.getToken();
  print("FCM Token: $token");

  // Μπορείς να το αποθηκεύσεις στο Firestore:
  // FirebaseFirestore.instance.collection('users').doc(userId).update({'fcmToken': token});
}


List<CameraDescription> cameras = [];

void startUploadingLocation(String userId) {
  Timer.periodic(const Duration(minutes: 1), (_) async {
    try {
  Position position = await Geolocator.getCurrentPosition();
  await FirebaseFirestore.instance.collection('users').doc(userId).update({
    'latitude': position.latitude,
    'longitude': position.longitude,
    'lastUpdated': FieldValue.serverTimestamp(),
  });
} catch (e) {
  print('Error getting location: $e');
}
  });
}

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();

  try {
    if (Firebase.apps.isEmpty) {
      await Firebase.initializeApp(
        options: DefaultFirebaseOptions.currentPlatform,
      );
    }
  } catch (e) {
    print('Firebase already initialized: $e');
  }

  try {
    cameras = await availableCameras();
  } on CameraException catch (e) {
    print('Error in fetching the cameras: $e');
  }

  runApp(const Unicars());
}







