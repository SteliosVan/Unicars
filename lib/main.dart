class Unicars extends StatefulWidget {
  const Unicars({super.key});

  @override
  State<Unicars> createState() => _UnicarsState();
}

class _UnicarsState extends State<Unicars> {
  @override
  void initState() {
    super.initState();
    _initLocationUpdates();
  }

  Future<void> _initLocationUpdates() async {
    final currentUser = FirebaseAuth.instance.currentUser;
    if (currentUser != null) {
      final granted = await Permission.location.request();
      if (granted.isGranted) {
        startUploadingLocation(currentUser.uid);
      } else {
        print('Location permission not granted');
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      theme: ThemeData.dark().copyWith(
        scaffoldBackgroundColor: const Color.fromARGB(255, 18, 32, 47),
      ),
      home: Scaffold(
        body: ListView(children: [
          LoadingScreen(),
        ]),
      ),
    );
  }
}


